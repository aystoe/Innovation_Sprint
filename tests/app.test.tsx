import { fireEvent, render, screen, within } from '@testing-library/react'
import { describe, expect, it, vi } from 'vitest'
import App from '../src/App'
import { CommunityProvider } from '../src/context/CommunityProvider'
import { preparePhoto } from '../src/services/photos'
vi.mock('../src/services/photos', () => ({ preparePhoto: vi.fn().mockResolvedValue('data:image/jpeg;base64,YWJj') }))
function start() { return render(<CommunityProvider><App /></CommunityProvider>) }
function register() {
  fireEvent.click(screen.getByRole('button', { name: 'Register', exact: true }))
  fireEvent.change(screen.getByRole('textbox', { name: /Name/ }), { target: { value: 'Hyein' } })
  fireEvent.change(screen.getByRole('textbox', { name: 'Which courses have you taken?' }), { target: { value: 'Innovation Sprint 26w' } })
  fireEvent.change(screen.getByRole('textbox', { name: 'Interests' }), { target: { value: 'Robotics' } })
  fireEvent.click(screen.getByRole('button', { name: /Continue to notification/ }))
  fireEvent.click(screen.getByRole('button', { name: 'Robotics' }))
  fireEvent.click(screen.getByRole('button', { name: 'Party' }))
  fireEvent.click(screen.getByRole('button', { name: /Finish registration/ }))
}
describe('complete React demo flows', () => {
  it('registers, saves notification choices, shows courses and updates participation', () => {
    start(); register()
    fireEvent.click(screen.getByRole('button', { name: /Coffee & familiar faces, open/ }))
    fireEvent.click(screen.getByRole('button', { name: 'Join event' }))
    fireEvent.click(screen.getByRole('button', { name: 'View your profile' }))
    expect(screen.getByRole('heading', { name: 'Hyein' })).toBeTruthy()
    expect(screen.getByText('Innovation Sprint 26w')).toBeTruthy()
    expect(screen.getByText('1', { selector: '.profile-stat strong' })).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: /Edit profile & notification/ }))
    fireEvent.click(screen.getByRole('button', { name: /Continue to notification/ }))
    expect(screen.getByRole('button', { name: 'Robotics' }).getAttribute('aria-pressed')).toBe('true')
    expect(screen.getByRole('button', { name: 'Party' }).getAttribute('aria-pressed')).toBe('true')
  })
  it('requires a name and preserves draft fields when returning from onboarding', () => {
    start(); fireEvent.click(screen.getByRole('button', { name: 'Register', exact: true }))
    fireEvent.change(screen.getByRole('textbox', { name: /Name/ }), { target: { value: '  ' } })
    fireEvent.submit(screen.getByRole('button', { name: /Continue to notification/ }).closest('form')!)
    expect(screen.getByRole('alert').textContent).toContain('enter your name')
    fireEvent.change(screen.getByRole('textbox', { name: /Name/ }), { target: { value: 'Hyein' } })
    fireEvent.click(screen.getByRole('button', { name: /Continue to notification/ }))
    fireEvent.click(screen.getByRole('button', { name: 'Workshop' }))
    fireEvent.click(screen.getByRole('button', { name: 'Back to your profile' }))
    expect((screen.getByRole('textbox', { name: /Name/ }) as HTMLInputElement).value).toBe('Hyein')
    fireEvent.click(screen.getByRole('button', { name: /Continue to notification/ }))
    expect(screen.getByRole('button', { name: 'Workshop' }).getAttribute('aria-pressed')).toBe('true')
  })
  it('opens sample profiles, restricts announcements and resets the demo', () => {
    start(); fireEvent.click(screen.getByRole('button', { name: 'View Maya Chen’s profile' }))
    expect(screen.getByRole('heading', { name: 'Maya Chen' })).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Back', exact: true }))
    fireEvent.click(screen.getByRole('button', { name: 'Announcements', exact: true }))
    expect(screen.getByText('For organizers only')).toBeTruthy()
    fireEvent.change(screen.getByRole('combobox', { name: 'Demo role' }), { target: { value: 'organizer' } })
    expect(screen.getByRole('heading', { name: 'Next cohort: organizer briefing' })).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Social Events' }))
    register()
    fireEvent.click(screen.getByRole('button', { name: 'Reset demo', exact: true }))
    fireEvent.click(screen.getByRole('button', { name: 'Reset demo data' }))
    expect(screen.getByRole('button', { name: 'Register', exact: true })).toBeTruthy()
  })
  it('publishes a targeted event to its selected feed', () => {
    start(); fireEvent.click(screen.getByRole('button', { name: 'Create an event' }))
    fireEvent.change(screen.getByRole('combobox', { name: 'Event type' }), { target: { value: 'job' } })
    fireEvent.change(screen.getByRole('textbox', { name: 'Title' }), { target: { value: 'Robotics internship' } })
    fireEvent.change(screen.getByRole('textbox', { name: 'Description' }), { target: { value: 'Build with us.' } })
    fireEvent.change(screen.getByRole('textbox', { name: 'Location' }), { target: { value: 'Munich' } })
    fireEvent.change(screen.getByLabelText('Starts / Opens'), { target: { value: '2030-01-01T10:00' } })
    fireEvent.change(screen.getByLabelText('Ends / Application deadline'), { target: { value: '2030-02-01T10:00' } })
    fireEvent.change(screen.getByRole('combobox', { name: 'Who can see this event?' }), { target: { value: 'targeted' } })
    fireEvent.click(screen.getByRole('checkbox', { name: 'Robotics', exact: true }))
    fireEvent.click(screen.getByRole('button', { name: 'Publish event' }))
    expect(screen.getByRole('heading', { name: 'Robotics internship' })).toBeTruthy()
    expect(screen.getByRole('button', { name: 'Opportunities', exact: true }).getAttribute('aria-current')).toBe('page')
  })
  it('posts text and photo reviews on an ended event', async () => {
    start(); fireEvent.click(screen.getByRole('button', { name: /Alumni Autumn Social, ended/ }))
    fireEvent.click(screen.getByRole('button', { name: 'Add a review' }))
    fireEvent.change(screen.getByRole('textbox', { name: 'Your experience' }), { target: { value: 'A great evening.' } })
    fireEvent.change(screen.getByLabelText('Choose review photos'), { target: { files: [new File(['photo'], 'memory.jpg', { type: 'image/jpeg' })] } })
    await screen.findByText('1 photo ready')
    expect(preparePhoto).toHaveBeenCalled()
    fireEvent.click(screen.getByRole('button', { name: 'Post review' }))
    expect(screen.getByText('A great evening.')).toBeTruthy()
    expect(screen.getByAltText('Photo 1 shared in this event review')).toBeTruthy()
    const review = screen.getByText('A great evening.').closest('article')!
    expect(within(review).getByText('You · Alumni')).toBeTruthy()
  })
})
